  function words(name) {
    const tokens = String(name).split("_");
    const result = [];
    for (let index = 0; index < tokens.length; ) {
      let found = false;
      for (let length = Math.min(4, tokens.length - index); length; length--) {
        const key = tokens.slice(index, index + length).join("_");
        if (terms[key]) {
          result.push(terms[key]);
          index += length;
          found = true;
          break;
        }
      }
      if (!found) result.push(tokens[index++]);
    }
    return result.join("");
  }
  function tableLabel(name) {
    if (name.startsWith("progress."))
      return words(name.slice(9)) + "（玩法记录）";
    if (/^[mt]_/.test(name))
      return (
        words(name.slice(2)) +
        (name[0] === "m" ? "（基础数据）" : "（存档数据）")
      );
    return words(name);
  }
  function fieldLabel(name) {
    return exactFields[name] || words(name.replace(/^[mt]_/, ""));
  }
  function displayValue(row, key) {
    return row?._display &&
      Object.prototype.hasOwnProperty.call(row._display, key)
      ? row._display[key]
      : row?.[key];
  }
  function preferredColumns(rows, maximum = 7) {
    const keys = [
      ...new Set(
        rows
          .slice(0, 20)
          .flatMap((row) => [
            ...Object.keys(row),
            ...(row._display?.name ? ["name"] : []),
          ]),
      ),
    ].filter((key) => !key.startsWith("_"));
    const priority = [
      "id",
      "name",
      "label",
      "player_name",
      "rarity",
      "level",
      "amount",
      "type",
      "quality_type",
      "status",
    ];
    return [
      ...priority.filter((key) => keys.includes(key)),
      ...keys.filter((key) => !priority.includes(key)),
    ].slice(0, maximum);
  }
  return { tableLabel, fieldLabel, displayValue, preferredColumns, terms };
